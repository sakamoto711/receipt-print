import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.charset.CharacterCodingException;
import java.nio.charset.Charset;
import java.nio.charset.CharsetEncoder;
import java.nio.charset.CodingErrorAction;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Map;
import java.util.TreeMap;

/** Generates the immutable commonMain CP932 reverse mapping table. */
public final class GenerateCp932Table {
    private static final String OFFICIAL_SOURCE =
        "https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WINDOWS/CP932.TXT";

    private GenerateCp932Table() {}

    public static void main(String[] args) throws Exception {
        if (args.length == 2 && args[0].equals("--verify-jdk-bootstrap")) {
            verifyJdkBootstrap(Path.of(args[1]));
            return;
        }
        if (args.length != 2) {
            throw new IllegalArgumentException(
                "usage: GenerateCp932Table <CP932.TXT|--jdk-bootstrap> <output.kt> " +
                    "or --verify-jdk-bootstrap <committed.kt>"
            );
        }

        var entries = new TreeMap<Integer, Integer>();
        String source;
        String sha256;
        if (args[0].equals("--jdk-bootstrap")) {
            source = "OpenJDK windows-31j Charset bootstrap";
            sha256 = "not-applicable";
            loadFromJdk(entries);
        } else {
            var input = Path.of(args[0]);
            source = OFFICIAL_SOURCE;
            sha256 = sha256(Files.readAllBytes(input));
            loadOfficialMapping(input, entries);
        }

        writeKotlin(Path.of(args[1]), entries, source, sha256);
    }

    private static void verifyJdkBootstrap(Path committed) throws Exception {
        Path generated = Files.createTempFile("Cp932MappingTable", ".kt");
        try {
            main(new String[] {"--jdk-bootstrap", generated.toString()});
            if (Files.mismatch(committed, generated) != -1L) {
                throw new IllegalStateException(
                    "Cp932MappingTable.kt is stale; regenerate it with tools/GenerateCp932Table.java"
                );
            }
        } finally {
            Files.deleteIfExists(generated);
        }
    }

    private static void loadOfficialMapping(Path input, Map<Integer, Integer> entries)
        throws IOException {
        for (var rawLine : Files.readAllLines(input)) {
            var line = rawLine.split("#", 2)[0].trim();
            if (line.isEmpty()) {
                continue;
            }
            var fields = line.split("\\s+");
            if (fields.length < 2 || !fields[0].startsWith("0x") || !fields[1].startsWith("0x")) {
                throw new IllegalArgumentException("Unexpected CP932.TXT line: " + rawLine);
            }
            var encoded = Integer.parseInt(fields[0].substring(2), 16);
            var codePoint = Integer.parseInt(fields[1].substring(2), 16);
            // CP932.TXT is byte-to-Unicode and contains duplicate Unicode mappings.
            // The first (lowest byte value) mapping is the deterministic encode form.
            entries.putIfAbsent(codePoint, encoded);
        }
    }

    private static void loadFromJdk(Map<Integer, Integer> entries)
        throws CharacterCodingException {
        CharsetEncoder encoder = Charset.forName("windows-31j")
            .newEncoder()
            .onMalformedInput(CodingErrorAction.REPORT)
            .onUnmappableCharacter(CodingErrorAction.REPORT);

        for (int codePoint = 0; codePoint <= 0xFFFF; codePoint++) {
            if (Character.isSurrogate((char) codePoint)) {
                continue;
            }
            String source = Character.toString((char) codePoint);
            if (!encoder.canEncode(source)) {
                continue;
            }
            encoder.reset();
            ByteBuffer encoded = encoder.encode(java.nio.CharBuffer.wrap(source));
            if (encoded.remaining() == 1) {
                entries.put(codePoint, encoded.get() & 0xFF);
            } else if (encoded.remaining() == 2) {
                entries.put(codePoint, ((encoded.get() & 0xFF) << 8) | (encoded.get() & 0xFF));
            } else {
                throw new IllegalStateException("Unexpected CP932 length for U+" + Integer.toHexString(codePoint));
            }
        }
    }

    private static void writeKotlin(
        Path output,
        Map<Integer, Integer> entries,
        String source,
        String sha256
    ) throws IOException {
        Files.createDirectories(output.getParent());
        var content = new StringBuilder();
        content.append("// Generated by tools/GenerateCp932Table.java. Do not edit manually.\n")
            .append("package receiptdsl.encoding\n\n")
            .append("internal object Cp932MappingTable {\n")
            .append("    internal const val source: String = \"")
            .append(escape(source))
            .append("\"\n")
            .append("    internal const val sha256: String = \"")
            .append(sha256)
            .append("\"\n\n")
            .append("    private const val entryWidth: Int = 8\n")
            .append("    private const val fieldWidth: Int = 4\n")
            .append("    private val packed: String = buildString {\n");
        appendPackedChunks(content, entries);
        content.append("    }\n\n")
            .append("    internal fun encodedValue(codePoint: Int): Int? {\n")
            .append("        var low = 0\n")
            .append("        var high = packed.length / entryWidth - 1\n")
            .append("        while (low <= high) {\n")
            .append("            val middle = (low + high).ushr(1)\n")
            .append("            val offset = middle * entryWidth\n")
            .append("            val current = readHex(offset)\n")
            .append("            when {\n")
            .append("                current < codePoint -> low = middle + 1\n")
            .append("                current > codePoint -> high = middle - 1\n")
            .append("                else -> return readHex(offset + fieldWidth)\n")
            .append("            }\n")
            .append("        }\n")
            .append("        return null\n")
            .append("    }\n\n")
            .append("    private fun readHex(offset: Int): Int {\n")
            .append("        var value = 0\n")
            .append("        for (index in offset until offset + fieldWidth) {\n")
            .append("            val digit = when (val character = packed[index]) {\n")
            .append("                in '0'..'9' -> character.code - '0'.code\n")
            .append("                in 'A'..'F' -> character.code - 'A'.code + 10\n")
            .append("                else -> error(\"Invalid generated CP932 hex digit: $character\")\n")
            .append("            }\n")
            .append("            value = (value shl 4) or digit\n")
            .append("        }\n")
            .append("        return value\n")
            .append("    }\n")
            .append("}\n");

        Files.writeString(output, content.toString());
    }

    private static void appendPackedChunks(StringBuilder output, Map<Integer, Integer> entries) {
        var chunk = new StringBuilder();
        int entryIndex = 0;
        for (var entry : entries.entrySet()) {
            chunk.append(String.format("%04X%04X", entry.getKey(), entry.getValue()));
            entryIndex++;
            if (entryIndex % 256 == 0 || entryIndex == entries.size()) {
                output.append("        append(\"").append(chunk).append("\")\n");
                chunk.setLength(0);
            }
        }
    }

    private static String escape(String value) {
        return value.replace("\\", "\\\\").replace("\"", "\\\"");
    }

    private static String sha256(byte[] bytes) throws NoSuchAlgorithmException {
        var digest = MessageDigest.getInstance("SHA-256").digest(bytes);
        var result = new StringBuilder();
        for (byte value : digest) {
            result.append(String.format("%02x", value & 0xFF));
        }
        return result.toString();
    }
}
